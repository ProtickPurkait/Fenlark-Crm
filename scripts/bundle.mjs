// ============================================================================
// Concatenates the migrations, in order, into dist/all_migrations.sql so the
// whole schema can be applied with one paste into the Supabase SQL editor
// instead of nine pastes that must not be reordered.
//
//   npm run bundle
//
// Generated — never edit dist/ by hand; edit the migrations and re-run.
// ============================================================================
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS = path.join(ROOT, 'supabase/migrations');
const OUT = path.join(ROOT, 'dist/all_migrations.sql');

const files = readdirSync(MIGRATIONS).filter((f) => f.endsWith('.sql')).sort();
if (files.length === 0) {
  console.error('No migrations found.');
  process.exit(1);
}

const rule = '='.repeat(76);
const parts = [
  `-- ${rule}`,
  '-- Fenlark CRM — complete schema, generated by scripts/bundle.mjs',
  '--',
  '-- DO NOT EDIT. Edit supabase/migrations/*.sql and run `npm run bundle`.',
  '--',
  '-- Before running this in the Supabase SQL editor, enable pg_cron:',
  '--   Dashboard > Database > Extensions > pg_cron',
  '-- Without it the schema still applies, but the stale-lead sweep is not',
  '-- scheduled and must be driven externally.',
  '--',
  `-- Sources (${files.length}), applied in this order:`,
  ...files.map((f) => `--   ${f}`),
  `-- ${rule}`,
  '',
];

for (const f of files) {
  parts.push('', `-- ${rule}`, `-- BEGIN ${f}`, `-- ${rule}`, '');
  parts.push(readFileSync(path.join(MIGRATIONS, f), 'utf8').trimEnd());
  parts.push('', `-- END ${f}`, '');
}

mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, parts.join('\n') + '\n', 'utf8');

const lines = parts.join('\n').split('\n').length;
console.log(`Bundled ${files.length} migrations into dist/all_migrations.sql (${lines} lines).`);
